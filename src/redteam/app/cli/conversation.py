"""Natural-language conversation facade for the interactive CLI.

This module makes the terminal feel like an agent conversation without
turning prose into an execution backdoor.  The model may explain, clarify,
or formulate an objective/guidance; concrete actions still have to be
generated by Orchestration, compiled against the tool catalog, authorized by
Control, and executed through the MCP gateway.

The UI deliberately asks for concise decision summaries, assumptions and a
short plan.  It never asks for or renders private chain-of-thought.
"""

