"""Natural-language conversation facade for the interactive CLI.

This module makes the terminal feel like an agent conversation without
turning prose into an execution backdoor.  The model may explain, clarify,
or formulate an objective/guidance; concrete actions still have to be
generated by Orchestration, compiled against the tool catalog, authorized by
Control, and executed through the MCP gateway.

The UI deliberately asks for concise decision summaries, assumptions and a
short plan.  It never asks for or renders private chain-of-thought.
"""

from __future__ import annotations

import asyncio
import json
import logging
import math
from typing import Any, Literal

from pydantic import BaseModel, Field, field_validator

from redteam.core.ports.llm import LLMClient
from redteam.core.redaction import redact_sensitive_text
from redteam.orchestration.cognition import (
    DecisionBudget,
    DecisionFailure,
    StructuredDecisionClient,
)
from redteam.orchestration.diagnostics import (
    DecisionDiagnostic,
    diagnostic_for_exception,
    error_type_for,
    exception_chain_for,
)
from redteam.orchestration.engagement_planner import sanitize_objective
from redteam.orchestration.state import RuntimeState

logger = logging.getLogger(__name__)

_SYSTEM_PROMPT = """You are the conversational front end of an authorized security-testing agent.
Return only the requested JSON object. Do not expose private chain-of-thought. Give a concise,
user-facing decision summary, explicit assumptions, and a short plan. Never claim that a tool has
already run. The runtime—not you—enforces scope, chooses executable MCP tools, requests approval,
and performs actions.

Write response, objective, guidance, assumptions, and plan in the same language as the user's
latest message. If the user writes in Korean, these fields MUST be natural Korean. Keep command,
tool, policy, target and error identifiers unchanged where translating them would alter meaning.

Choose mode:
- execute: a concrete request for a NEW investigation; set investigation="new";
- answer: a question that can be answered from the supplied session context;
- clarify: essential target or intent information is missing;
- guidance: advice that should influence the currently running agent without
  directly invoking a tool; set investigation="current".
Do not combine a request for a different investigation with current guidance.
Questions are read-only. If an instruction refers to an ended investigation,
clarify whether a follow-up is wanted; do not silently start a new investigation.
The supplied input binding is authoritative; never invent or change a run ID.
Tool availability is distinct from execution permission. A configured server or a shell
prepared at Run startup is not a discovered live tool. An empty tools list with availability
state configured_unverified or not_inspected means discovery has not happened, not that MCP
is absent. Use the supplied policy constraints; do not claim connectivity or permission.
"""


class ConversationDecision(BaseModel):
    """Safe, displayable result of interpreting one chat message."""

    mode: Literal["execute", "answer", "clarify", "guidance"]
    investigation: Literal["current", "new"] | None = None
    response: str = Field(min_length=1, max_length=2000)
    objective: str | None = Field(default=None, max_length=1000)
    guidance: str | None = Field(default=None, max_length=1000)
    assumptions: list[str] = Field(default_factory=list, max_length=5)
    plan: list[str] = Field(default_factory=list, max_length=6)

    @field_validator("response", "objective", "guidance")
    @classmethod
    def _redact_text(cls, value: str | None) -> str | None:
        if value is None:
            return None
        return redact_sensitive_text(value).strip()

    @field_validator("assumptions", "plan")
    @classmethod
    def _redact_items(cls, value: list[str]) -> list[str]:
        return [
            redact_sensitive_text(str(item)).strip()[:500] for item in value if str(item).strip()
        ]


_CONVERSATION_STAGE = "conversation_decide"
_DECISION_SCHEMA = ConversationDecision.model_json_schema()


class ConversationError(Exception):
    """Raised when the dialogue model cannot produce a displayable decision.

    Transport, schema, and classification failures are delivered as this
    error with zero executions. The diagnostic attribute carries the safe
    DecisionDiagnostic (stage, kind, code, rule, location, provider status,
    attempt counts and the nested last cause). It never carries provider
    bodies, prompts, keys, or exception messages. Callers chain the original
    exception with from exc. asyncio.CancelledError is never converted to
    this error and always propagates.
    """

    def __init__(
        self,
        message: str = "conversation decision failed",
        *,
        diagnostic: DecisionDiagnostic | None = None,
    ) -> None:
        super().__init__(message)
        self.diagnostic = diagnostic


def conversation_failure_label(
    diagnostic: DecisionDiagnostic | None, *, fallback: str = "unknown"
) -> str:
    """One operator-facing line built only from safe diagnostic fields."""

    if diagnostic is None:
        return fallback
    cause = diagnostic.last_cause
    rule = next((str(item.get("rule") or "") for item in diagnostic.validation_issues[:1]), "")
    location = diagnostic.location
    if cause is not None:
        if not rule:
            rule = next(
                (str(item.get("rule") or "") for item in cause.validation_issues[:1]), ""
            )
        location = location or cause.location
    parts = [diagnostic.code, diagnostic.stage, diagnostic.kind]
    if diagnostic.attempts:
        parts.append(f"attempts {diagnostic.attempts}")
    if cause is not None:
        parts.append(f"cause {cause.code}")
    if rule:
        parts.append(f"rule {rule}")
    if location:
        parts.append(f"at {location}")
    status = diagnostic.provider_status
    if status is None and cause is not None:
        status = cause.provider_status
    if status is not None:
        parts.append(f"status {status}")
    if diagnostic.error_type:
        parts.append(f"type {diagnostic.error_type}")
    return " · ".join(part for part in parts if part)


def _timeout_diagnostic(
    timeout_seconds: float, exc: BaseException, budget: DecisionBudget
) -> DecisionDiagnostic:
    """Outer-deadline cause that keeps the request-local counters the budget recorded."""

    return DecisionDiagnostic(
        code="conversation_timeout",
        stage=_CONVERSATION_STAGE,
        kind="transport",
        attempts=budget.used,
        summary=f"The conversation decision did not finish within {timeout_seconds:g} seconds.",
        retryable=False,
        last_cause=budget.last_failure,
        error_type=error_type_for(exc),
        exception_chain=exception_chain_for(exc),
        **budget.diagnostic_details(),
    )


def _unexpected_diagnostic(exc: BaseException) -> DecisionDiagnostic:
    attached = getattr(exc, "diagnostic", None)
    if isinstance(attached, DecisionDiagnostic):
        return attached
    return DecisionDiagnostic(
        code="conversation_failed",
        stage=_CONVERSATION_STAGE,
        kind="unknown",
        summary="The conversation decision failed before a valid reply was produced.",
        retryable=False,
        error_type=error_type_for(exc),
        exception_chain=exception_chain_for(exc),
    )


class ConversationAssistant:
    """Maintains bounded chat history and delegates interpretation to the configured LLM.

    timeout_seconds bounds one whole decision chain (default 180 s).
    max_attempts is the shared normal plus repair request total (default 6).
    transport_limit caps transport retries inside that total (default 5) and
    is counted apart from format and semantic repairs. These are constructor
    semantics; global OrchestrationSettings are not read here.

    Each decide call builds its own DecisionBudget from these values, so
    concurrent calls never share counters, and the outer timeout keeps the
    budget's counters when it cancels a call.
    """

    def __init__(
        self,
        llm: LLMClient,
        *,
        timeout_seconds: float = 180.0,
        max_attempts: int = 6,
        transport_limit: int = 5,
    ) -> None:
        timeout = float(timeout_seconds)
        if not math.isfinite(timeout) or timeout <= 0:
            raise ValueError("timeout_seconds must be finite and > 0")
        if int(transport_limit) < 0:
            raise ValueError("transport_limit must be non-negative")
        self._llm = llm
        self._timeout_seconds = timeout
        self._max_attempts = int(max_attempts)
        self._transport_limit = int(transport_limit)
        self._history: list[dict[str, str]] = []
        self._client = StructuredDecisionClient(
            self._llm,
            max_attempts=self._max_attempts,
            transport_limit=self._transport_limit,
        )

    async def decide(
        self,
        user_message: str,
        *,
        engagement_name: str,
        scope: list[str],
        tools: list[str] | None = None,
        tool_availability: dict | None = None,
        session_context: str = "No previous run in this session.",
        run_active: bool = False,
        prefer_execute: bool = False,
        llm_override: LLMClient | None = None,
    ) -> ConversationDecision:
        """Interpret one chat turn without selecting or invoking a tool.

        The model always decides through the shared structured-decision
        helper. No tool is selected, invoked, or approved here.
        ``prefer_execute`` is accepted for compatibility but never forces
        a mode conversion.
        """

        safe_message = sanitize_objective(user_message)
        tool_labels = list(tools or [])
        payload = {
            "engagement": redact_sensitive_text(engagement_name),
            "scope": list(scope[:20]),
            "tools": tool_labels[:40],
            "tool_availability": tool_availability or {"state": "not_inspected"},
            "run_active": bool(run_active),
            "session_context": redact_sensitive_text(session_context)[:3000],
            "user_message": safe_message,
            "history": list(self._history[-16:]),
        }
        # One budget per decide call: concurrent inputs never share counters, and
        # the outer timeout can cancel the call without losing them.
        budget = DecisionBudget(
            self._max_attempts,
            transport_limit=self._transport_limit,
            timeout_seconds=self._timeout_seconds,
        )
        try:
            # Request-local override: concurrent inputs never swap the shared
            # assistant's client or leak a previous Run's accounting context.
            client = self._client if llm_override is None else StructuredDecisionClient(
                llm_override,
                max_attempts=self._max_attempts,
                transport_limit=self._transport_limit,
            )
            # Two deadlines race by design: this outer timeout and the budget deadline
            # checked between attempts and used as the per-attempt timeout. Either may
            # fire first. The outer path reports conversation_timeout, the budget path
            # reports decision_time_budget_exhausted; both keep the budget counters.
            raw = await asyncio.wait_for(
                client.ask(
                    stage="conversation_decide",
                    payload=payload,
                    response_schema=ConversationDecision.model_json_schema(),
                    system=_SYSTEM_PROMPT,
                    budget=budget,
                ),
                timeout=self._timeout_seconds,
            )
        except asyncio.CancelledError:
            raise
        except asyncio.TimeoutError as exc:
            raise ConversationError(
                f"conversation decision timed out after {self._timeout_seconds:g}s",
                diagnostic=_timeout_diagnostic(self._timeout_seconds, exc, budget),
            ) from exc
        except DecisionFailure as exc:
            diagnostic = (
                exc.diagnostic
                if isinstance(exc.diagnostic, DecisionDiagnostic)
                else _unexpected_diagnostic(exc)
            )
            if diagnostic.code == "decision_time_budget_exhausted":
                message = (
                    f"conversation decision timed out after {self._timeout_seconds:g}s "
                    f"attempts={diagnostic.attempts} code={diagnostic.code}"
                )
            else:
                message = (
                    f"conversation decision failed kind={exc.kind} "
                    f"stage={exc.stage} attempts={exc.attempts} code={diagnostic.code}"
                )
            raise ConversationError(message, diagnostic=diagnostic) from exc
        except ConversationError:
            raise
        except Exception as exc:
            raise ConversationError(
                f"conversation decision failed {type(exc).__name__}",
                diagnostic=_unexpected_diagnostic(exc),
            ) from exc
        try:
            decision = ConversationDecision.model_validate(raw)
        except Exception as exc:
            raise ConversationError(
                f"invalid conversation decision {type(exc).__name__}",
                diagnostic=diagnostic_for_exception(
                    exc, stage=_CONVERSATION_STAGE, schema=_DECISION_SCHEMA
                ),
            ) from exc
        if decision.mode == "execute" and not decision.objective:
            decision = decision.model_copy(update={"objective": safe_message})
        if decision.mode == "guidance" and not decision.guidance:
            decision = decision.model_copy(update={"guidance": safe_message})
        self._remember(safe_message, decision)
        return decision

    async def final_response(self, state: RuntimeState) -> str:
        """Produce a concise user-facing result from safe runtime summaries.

        Uses only the actual terminal state and recent public
        observations. Makes zero LLM calls and has no Fake special case.
        """

        reason = state.termination_reason or state.phase.value
        recent = state.recent_observations[-5:]
        lines: list[str] = []
        if self._uses_korean():
            lines.append(
                f"Run이 {reason} 상태로 끝났습니다. "
                f"총 {state.actions_executed}개의 Action을 실행했습니다."
            )
            for item in recent:
                lines.append(f"- {item.summary}")
            if state.pending_approval_id is not None:
                lines.append(f"승인 대기: {state.pending_approval_id}")
        else:
            lines.append(f"Run ended as {reason} with {state.actions_executed} action(s).")
            for item in recent:
                lines.append(f"- {item.summary}")
            if state.pending_approval_id is not None:
                lines.append(f"Approval pending: {state.pending_approval_id}")
        safe = redact_sensitive_text("\n".join(lines)).strip()
        return safe[:3000] or reason

    def _remember(self, user_message: str, decision: ConversationDecision) -> None:
        self._history.extend(
            [
                {"role": "user", "content": user_message[:2000]},
                {
                    "role": "assistant",
                    "content": json.dumps(decision.model_dump(mode="json"), ensure_ascii=False),
                },
            ]
        )
        self._history = self._history[-16:]

    def _uses_korean(self) -> bool:
        seen_user = False
        for entry in self._history:
            if entry.get("role") != "user":
                continue
            seen_user = True
            content = str(entry.get("content") or "")
            for ch in content:
                if "\uAC00" <= ch <= "\uD7A3":
                    return True
        return True if not seen_user else False


def catalog_tool_labels(catalog: Any) -> list[str]:
    """Return bounded human labels from a gateway/catalog when enumerable."""

    all_tools = getattr(catalog, "all", None)
    if not callable(all_tools):
        return []
    try:
        descriptors = all_tools()
    except Exception:  # noqa: BLE001 - UI metadata must never block a run
        return []
    labels: list[str] = []
    for descriptor in descriptors[:40]:
        operations = ",".join(getattr(descriptor, "operations", [])[:4])
        label = f"{descriptor.server_id}/{descriptor.tool_name}"
        if operations:
            label += f" [{operations}]"
        labels.append(label[:300])
    return labels
