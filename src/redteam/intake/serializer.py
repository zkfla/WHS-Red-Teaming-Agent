"""Draft <-> real Contract model conversion (section 5): the LLM never
writes YAML. It only ever produces an :class:`EngagementDraft`; this
module is the one place that turns a *complete* draft into the
project's real, existing config models
(``redteam.core.config.EngagementConfig`` and
``redteam.core.contracts.engagement.*``) and serializes those with
``yaml.safe_dump`` — never a hand-built string.

    EngagementDraft -> (validate) -> EngagementConfig -> yaml.safe_dump

No new "Engagement-like" model is introduced beyond the temporary
``EngagementDraft`` itself.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import yaml

from redteam.core.config import EngagementConfig
from redteam.core.contracts.engagement import (
    ApprovalPolicy,
    EngagementScope,
    ExecutionBudget,
    RateLimitPolicy,
    RuleOfEngagement,
)
from redteam.intake.models import EngagementDraft, missing_required_fields

#: Marks an Engagement produced by this assistant, so a later `Edit` can
#: tell whether round-tripping it back into a draft is safe (see
#: `engagement_config_to_draft`).
_INTAKE_SOURCE_TAG = "intake-assistant"
_GENERATED_RULE_NAME = "intake-generated"


class DraftIncompleteError(ValueError):
    def __init__(self, missing: list[str]) -> None:
        self.missing = missing
        super().__init__(f"draft is missing required fields: {', '.join(missing)}")


class UnsafeEditError(ValueError):
    """Raised instead of silently discarding hand-authored ROE rules the
    Intake Assistant did not create -- see module docstring on
    `engagement_config_to_draft`."""


def merge_draft(old: EngagementDraft, new: EngagementDraft) -> EngagementDraft:
    """JSON-Merge-Patch-like field update (section 12): a field on
    ``new`` that is ``None`` or an empty list means "no new information
    this turn", not "clear this field" -- clearing an existing scope
    entry is a deliberate action better done via ``New``, not a
    same-session patch. Every non-empty field on ``new`` replaces the
    old value wholesale (lists are not deep-merged element by element).
    """

    merged = old.model_dump()
    for key, value in new.model_dump().items():
        if value is None:
            continue
        if isinstance(value, list) and not value:
            continue
        merged[key] = value
    return EngagementDraft.model_validate(merged)


@dataclass
class DraftConversionResult:
    engagement_config: EngagementConfig
    #: `denied_operations` entries that were not real canonical
    #: `"<capability>.<operation>"` keys -- moved into the ROE `notes`
    #: text instead of being silently dropped or guessed at (section 6).
    unenforced_operations: list[str] = field(default_factory=list)


def draft_to_engagement_config(draft: EngagementDraft) -> DraftConversionResult:
    """The only path from a draft to a real, loadable ``EngagementConfig``.

    Raises :class:`DraftIncompleteError` if required fields are still
    missing -- callers must check :func:`missing_required_fields`
    (or catch this) before offering Preflight.
    """

    missing = missing_required_fields(draft)
    if missing:
        raise DraftIncompleteError(missing)

    from redteam.core.action_semantics import canonical_action_key

    enforced_operations: list[str] = []
    unenforced_operations: list[str] = []
    for key in draft.denied_operations:
        capability, _, operation = key.partition(".")
        try:
            canonical_action_key(capability, operation)
        except ValueError:
            unenforced_operations.append(key)
        else:
            enforced_operations.append(key)

    notes_parts = list(draft.notes)
    if unenforced_operations:
        notes_parts.append(
            "Also requested by the operator but NOT enforced (unrecognized "
            "canonical operation): " + ", ".join(unenforced_operations)
        )

    rule = RuleOfEngagement(
        name=_GENERATED_RULE_NAME,
        description="Generated by the Engagement Intake Assistant.",
        allowed_capabilities=list(draft.allowed_capabilities),
        denied_capabilities=list(draft.denied_capabilities),
        denied_operations=enforced_operations,
        availability_impact_allowed=bool(draft.availability_impact_allowed),
        notes="; ".join(notes_parts),
    )

    assert draft.name is not None  # noqa: S101 - guaranteed by missing_required_fields above
    assert draft.max_actions is not None  # noqa: S101 - same

    engagement_config = EngagementConfig(
        name=draft.name,
        description=draft.description or "",
        scope=EngagementScope(
            allowed_hosts=list(draft.allowed_hosts),
            allowed_domains=list(draft.allowed_domains),
            allowed_networks=list(draft.allowed_networks),
        ),
        rules_of_engagement=[rule],
        execution_budget=ExecutionBudget(
            max_actions=draft.max_actions,
            max_tool_calls=draft.max_tool_calls,
            max_duration_seconds=draft.max_duration_seconds,
        ),
        rate_limit_policy=RateLimitPolicy(max_actions_per_minute=30),
        approval_policy=ApprovalPolicy(),
        metadata={
            "focus_areas": list(draft.focus_areas),
            "source": _INTAKE_SOURCE_TAG,
            **({"objective": draft.objective} if draft.objective else {}),
        },
    )
    return DraftConversionResult(
        engagement_config=engagement_config, unenforced_operations=unenforced_operations
    )


def engagement_config_to_draft(config: EngagementConfig) -> EngagementDraft:
    """Best-effort reverse of :func:`draft_to_engagement_config`, for
    seeding an ``Edit`` session from an existing config.

    Refuses (raises :class:`UnsafeEditError`) when the existing config
    was not produced by this assistant or carries more than the one
    rule it generates -- round-tripping an operator's own hand-authored
    ROE rules through this lossy draft shape would silently discard
    fields the Intake Assistant knows nothing about (section 12: never
    silently drop existing scope/rules). Those configs still work with
    ``redteam run``/``redteam validate`` exactly as before; they just
    are not natural-language-editable in place.
    """

    if config.metadata.get("source") != _INTAKE_SOURCE_TAG:
        raise UnsafeEditError(
            "this engagement.yaml was not generated by the Intake Assistant "
            "-- edit the YAML directly, or use `redteam` -> New to start a "
            "fresh intake-managed engagement"
        )
    if len(config.rules_of_engagement) > 1:
        raise UnsafeEditError(
            "this engagement.yaml has more than one rules_of_engagement "
            "entry -- natural-language edit could not safely represent all "
            "of them, so it refuses rather than dropping any"
        )
    rule = config.rules_of_engagement[0] if config.rules_of_engagement else None

    return EngagementDraft(
        name=config.name,
        description=config.description or None,
        objective=config.metadata.get("objective"),
        allowed_hosts=list(config.scope.allowed_hosts),
        allowed_domains=list(config.scope.allowed_domains),
        allowed_networks=list(config.scope.allowed_networks),
        focus_areas=list(config.metadata.get("focus_areas", [])),
        allowed_capabilities=list(rule.allowed_capabilities) if rule else [],
        denied_capabilities=list(rule.denied_capabilities) if rule else [],
        denied_operations=list(rule.denied_operations) if rule else [],
        availability_impact_allowed=rule.availability_impact_allowed if rule else None,
        notes=[rule.notes] if rule and rule.notes else [],
        max_actions=config.execution_budget.max_actions,
        max_tool_calls=config.execution_budget.max_tool_calls,
        max_duration_seconds=config.execution_budget.max_duration_seconds,
    )


def dump_engagement_yaml(config: EngagementConfig) -> str:
    """The one place a draft's resulting config becomes YAML text --
    always through the real Pydantic model's ``model_dump()``, never a
    hand-built string (section 5)."""

    return yaml.safe_dump(config.model_dump(mode="json"), sort_keys=False)


ScopeDiff = dict[str, tuple[list[str], list[str]]]


def scope_diff(old: EngagementDraft, new: EngagementDraft) -> ScopeDiff:
    """``{field: (added, removed)}`` for the three scope list fields --
    shown to the user before an edit is applied (section 6: scope
    changes are never silent)."""

    diff: ScopeDiff = {}
    for field_name in ("allowed_hosts", "allowed_domains", "allowed_networks"):
        old_values = set(getattr(old, field_name))
        new_values = set(getattr(new, field_name))
        added = sorted(new_values - old_values)
        removed = sorted(old_values - new_values)
        if added or removed:
            diff[field_name] = (added, removed)
    return diff
