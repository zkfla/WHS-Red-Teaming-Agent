"""Declarative verification: what the result must look like.

Stated before the action runs and stored on the Hypothesis, then mapped
to a ``Verdict`` — a different axis from ``ToolResult.success``.
Rationale: ``docs/agent/orchestration.md``.
"""

from __future__ import annotations

from enum import Enum
from typing import Any, Literal

from pydantic import BaseModel, model_validator

from redteam.core.contracts.tool import ToolResult
from redteam.core.enums import Verdict

ExpectationKind = Literal[
    "tool_succeeded",
    "output_field_present",
    "output_field_equals",
    "output_contains",
]


class ExpectationOutcome(str, Enum):
    MET = "met"
    NOT_MET = "not_met"
    INDETERMINATE = "indeterminate"


def _output_mapping(result: ToolResult) -> dict[str, Any] | None:
    return result.output if isinstance(result.output, dict) else None


class Expectation(BaseModel):
    """What the result must look like, decided before the action runs."""

    kind: ExpectationKind = "tool_succeeded"
    field: str = ""
    value: Any = None
    description: str = ""

    #: Meeting this expectation *is* the security violation.
    violation_if_met: bool = False
    #: Not meeting it is itself suspicious (rather than simply "no finding").
    anomaly_if_unmet: bool = False

    @model_validator(mode="after")
    def _field_required_for_field_kinds(self) -> Expectation:
        if self.kind in ("output_field_present", "output_field_equals") and not self.field:
            raise ValueError(f"expectation kind {self.kind!r} needs a field name")
        if self.kind == "output_contains" and self.value is None:
            raise ValueError("expectation kind 'output_contains' needs a value to look for")
        return self

    def evaluate(self, result: ToolResult) -> ExpectationOutcome:
        if self.kind == "tool_succeeded":
            return ExpectationOutcome.MET if result.success else ExpectationOutcome.NOT_MET

        if self.kind == "output_contains":
            if result.output is None:
                return ExpectationOutcome.INDETERMINATE
            return (
                ExpectationOutcome.MET
                if str(self.value) in str(result.output)
                else ExpectationOutcome.NOT_MET
            )

        mapping = _output_mapping(result)
        if mapping is None:
            # A non-dict output cannot answer a field question either way.
            return ExpectationOutcome.INDETERMINATE

        if self.kind == "output_field_present":
            return (
                ExpectationOutcome.MET
                if self.field in mapping
                else ExpectationOutcome.NOT_MET
            )

        if self.field not in mapping:
            return ExpectationOutcome.INDETERMINATE
        return (
            ExpectationOutcome.MET
            if mapping[self.field] == self.value
            else ExpectationOutcome.NOT_MET
        )


def verdict_for(expectation: Expectation | None, result: ToolResult) -> tuple[Verdict, str]:
    """Map a result to a ``Verdict`` plus the sentence explaining it.

    The reason is generated by code, never by a model.
    """
    if not result.success:
        code = result.error.code if result.error else "unknown_error"
        return Verdict.UNKNOWN, f"tool execution failed ({code}) — no verdict can be reached"

    if expectation is None:
        return Verdict.PASS, "tool executed successfully; no expectation was under test"

    outcome = expectation.evaluate(result)
    label = expectation.description or (
        f"{expectation.kind}({expectation.field or expectation.value})"
    )

    if outcome is ExpectationOutcome.INDETERMINATE:
        return Verdict.UNKNOWN, f"expectation could not be evaluated against the output: {label}"

    if outcome is ExpectationOutcome.MET:
        if expectation.violation_if_met:
            return Verdict.VIOLATION, f"expectation met and it is a violation: {label}"
        return Verdict.PASS, f"expectation met, benign: {label}"

    if expectation.anomaly_if_unmet:
        return Verdict.ANOMALY, f"expectation not met, which is itself unexpected: {label}"
    return Verdict.PASS, f"expectation not met; hypothesis not confirmed: {label}"
